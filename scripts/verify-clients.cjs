const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4173');
  await page.locator('#add-client-button').click();
  await page.screenshot({ path: 'verification/client-form-desktop.png' });
  await page.locator('#save-client').click();
  assert.equal(await page.locator('#client-dialog').evaluate(e => e.open), true);
  await page.locator('#client-name').fill('Huellitas <Spa>');
  await page.locator('[name="phone"]').fill('123');
  await page.locator('#save-client').click();
  assert.match(await page.locator('#client-form-error').innerText(), /10 dígitos/);
  await page.locator('[name="phone"]').fill('+57 300 123 4567');
  await page.locator('[name="address"]').fill('Calle 10 #20-30');
  await page.locator('#client-logo').setInputFiles('assets/matius-clean.png');
  await page.locator('#client-logo-preview img').waitFor();
  await page.locator('#save-client').click();
  assert.equal(await page.locator('.client-card').count(), 6);
  assert.equal(await page.locator('#client-count').innerText(), '6');
  assert.equal(await page.locator('.expanded .client-name strong').innerText(), 'Huellitas <Spa>');
  assert.equal(await page.locator('.expanded .source-link').count(), 0);
  await page.locator('.expanded [data-add]').click();
  assert.match(await page.locator('#order-dialog .modal-heading').innerText(), /Huellitas <Spa>/);
  await page.locator('[data-product="statik"]').click();
  await page.locator('#save-order').click();
  await page.reload();
  await page.locator('#search').fill('3001234567');
  assert.equal(await page.locator('.client-card').count(), 1);
  assert.equal(await page.locator('.client-logo img').evaluate(e => e.src.startsWith('data:image/') && e.complete && e.naturalWidth > 0), true);
  await page.locator('.client-toggle').click();
  assert.match(await page.locator('.order-total').innerText(), /30\.000/);
  await page.locator('#add-client-button').click();
  await page.locator('#client-name').fill('Huellitas <Spa>');
  await page.locator('[name="phone"]').fill('3001234567');
  await page.locator('#save-client').click();
  assert.match(await page.locator('#client-form-error').innerText(), /Ya existe/);
  await page.locator('#client-dialog [data-close]').first().click();
  await page.locator('#search').fill('');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#add-client-button').click();
  await page.screenshot({ path: 'verification/client-form-mobile.png' });
  assert.equal(await page.locator('#client-dialog').evaluate(e => e.scrollWidth > e.clientWidth), false);
  await page.locator('#client-name').fill('Nuevo Spa');
  await page.locator('[name="phone"]').fill('3101234567');
  await page.locator('#save-client').click();
  assert.equal(await page.locator('.expanded .client-initials').innerText(), 'NS');
  assert.equal(await page.locator('.client-card').count(), 7);
  for (const width of [320,390,768]) {
    await page.setViewportSize({width,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const heading = await page.locator('.clients-heading h1').boundingBox();
    const button = await page.locator('#add-client-button').boundingBox();
    assert.ok(button.x >= heading.x + heading.width - 1);
  }
  // A failed local write must preserve the form and must not add a client.
  await page.locator('#add-client-button').click();
  await page.locator('#client-name').fill('No guardado');
  await page.locator('[name="phone"]').fill('3201234567');
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError'); }; });
  await page.locator('#save-client').click();
  assert.match(await page.locator('#client-form-error').innerText(), /No se pudo guardar/);
  assert.equal(await page.locator('.client-card').count(), 7);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: validation, image upload, escaped names, persistence, new-client orders, duplicate prevention, initials, mobile layout, failed-storage handling.');
})().catch(error => { console.error(error); process.exit(1); });
