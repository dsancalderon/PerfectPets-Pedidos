const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  await page.goto('http://127.0.0.1:4173');
  assert.equal(await page.locator('.client-card').count(), 5);
  assert.equal(await page.getByText('CERCA DE QUIENES LOS CUIDAN').count(), 0);
  assert.equal(await page.locator('.last-order').filter({ hasText: 'Sin pedidos' }).count(), 5);
  fs.mkdirSync('verification', { recursive: true });
  await page.screenshot({ path: 'verification/desktop.png', fullPage: true });
  await page.locator('[data-client="matius"]').click();
  await page.locator('[data-add="matius"]').click();
  assert.equal(await page.locator('#save-order').isDisabled(), true);
  await page.locator('[data-size="xtreme"]').selectOption('4 L');
  await page.locator('[data-product="xtreme"]').click();
  await page.locator('[data-product="xtreme"]').click();
  await page.locator('[data-product="statik"]').click();
  assert.match(await page.locator('#draft-total').innerText(), /210\.000/);
  await page.locator('#order-date').fill('2026-10-15');
  await page.locator('#order-notes').fill('Pedido de prueba <seguro>');
  await page.screenshot({ path: 'verification/order-desktop.png', fullPage: true });
  await page.locator('#save-order').click();
  assert.match(await page.locator('.order-total').innerText(), /210\.000/);
  assert.match(await page.locator('.order-date').innerText(), /15 de octubre de 2026/);
  await page.reload();
  await page.locator('[data-client="matius"]').click();
  assert.equal(await page.locator('.order').count(), 1);
  assert.equal(await page.locator('.order-notes').innerText(), 'Pedido de prueba <seguro>');
  await page.locator('[data-edit]').click();
  assert.equal(await page.locator('#order-date').inputValue(), '2026-10-15');
  await page.locator('[data-quantity="0"]').fill('3');
  await page.locator('[data-quantity="0"]').press('Tab');
  assert.match(await page.locator('#draft-total').innerText(), /300\.000/);
  await page.locator('#order-date').fill('2026-11-01');
  await page.locator('#save-order').click();
  assert.match(await page.locator('.order-total').innerText(), /300\.000/);
  assert.match(await page.locator('.order-date').innerText(), /1 de noviembre de 2026/);
  await page.locator('[data-delete]').click();
  await page.locator('#delete-dialog [data-close]').click();
  assert.equal(await page.locator('.order').count(), 1);
  await page.locator('[data-delete]').click();
  await page.locator('#confirm-delete').click();
  assert.equal(await page.locator('.order').count(), 0);
  await page.reload();
  assert.equal(await page.locator('.last-order').filter({ hasText: 'Sin pedidos' }).count(), 5);
  await page.locator('#search').fill('324890');
  assert.equal(await page.locator('.client-card').count(), 1);
  await page.locator('#search').fill('no existe');
  assert.equal(await page.locator('.no-results').count(), 1);
  await page.locator('#clear-search').click();
  await page.locator('#catalog-button').click();
  assert.equal(await page.locator('#catalog-dialog .product-card').count(), 6);
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'verification/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.locator('[data-client="matius"]').click();
  await page.screenshot({ path: 'verification/mobile-expanded.png', fullPage: true });
  await page.locator('[data-add="matius"]').click();
  const dateBox = await page.locator('#order-date').boundingBox();
  assert.ok(dateBox.y >= 0 && dateBox.y + dateBox.height <= 844, 'Date visible on mobile when opening form');
  await page.locator('#order-date').fill('2026-10-20');
  await page.screenshot({ path: 'verification/order-mobile-date.png', fullPage: true });
  await page.locator('[data-product="frutos"]').click();
  await page.locator('#save-order').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'verification/order-mobile.png', fullPage: true });
  assert.equal(await page.locator('#order-dialog').evaluate(el => el.scrollWidth > el.clientWidth), false);
  await page.locator('#save-order').click();
  assert.match(await page.locator('.order-total').innerText(), /90\.000/);
  assert.match(await page.locator('.order-date').innerText(), /20 de octubre de 2026/);
  for (const width of [320, 768, 1024]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, `Overflow at ${width}`);
  }
  await page.evaluate(() => localStorage.removeItem('perfect-pets.orders.v1'));
  await page.reload();
  assert.equal(await page.locator('img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0)), true);
  assert.deepEqual(errors, []);
  console.log('PASS: client data, create, totals, edit, persistence, safe notes, delete/cancel, search, catalog, mobile order, 320–1440px overflow, images, browser errors.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
